/** Build the upstream UI's native protocol adapter for the Server transport.
 * The UI implementation remains the source of truth for message/tool/event mapping.
 */
import { readFile, mkdir, writeFile, copyFile } from 'node:fs/promises';
import { resolve, dirname } from 'node:path';
const sourcePath = resolve(import.meta.dir, '../../app/src/app/lib/opencode-v2-adapter.ts');
const outputDir = resolve(import.meta.dir, '../src/tron-compat');
let source = await readFile(sourcePath, 'utf8');
source = source
  .replace(/^import .* from "\.\/opencode";\n/m, '')
  .replace(/^import .* from "\.\/runtime-env";\n/m, '')
  .replace(/^import .* from "\.\.\/utils";\n/m, '')
  .replace(/function createV2Fetch\([\s\S]*?\n}\n/, '')
  .replace(/const v2Clients = [\s\S]*?(?=\/\*\* Whether each engine)/, '')
  .replace('auth: { token?: string },\n)', 'auth: { token?: string },\n  fetchImpl: typeof fetch,\n)')
  .replace('  const fetchImpl = createV2Fetch(auth);\n', '')
  .replace(/  const compatibilityClient = createClient\([^\n]+\n/, '')
  .replace(/  Object.assign\(compatibilityClient.global,[\s\S]*?v2Clients.add\(compatibilityClient\);\n/, '')
  .replace('Object.assign(compatibilityClient, {', 'Object.assign(adapter, {');
source = 'function normalizeDirectoryPath(value: string) { return value.replace(/\\\\/g, "/").replace(/\\/+$/, ""); }\n' + source;
if (/compatibilityClient|createDesktopFetch|createV2Fetch|const v2Clients/.test(source)) throw new Error('Upstream client transport changed: review the Server adapter build.');
await mkdir(outputDir, {recursive:true});
const result = await Bun.build({
  entrypoints: [sourcePath], target: 'bun', format: 'esm', minify: false,
  plugins: [{name:'server-native-transport', setup(build) {
    build.onLoad({filter:/opencode-v2-adapter\.ts$/}, () => ({contents:source,loader:'ts'}));
  }}],
});
if (!result.success) throw new AggregateError(result.logs, 'Cannot build native client');
const output = '// Generated by scripts/build-tron-client.ts from the upstream native adapter.\n' + await result.outputs[0].text();
await writeFile(resolve(outputDir,'client.js'),output);
const dist = resolve(import.meta.dir,'../dist/tron-compat/client.js');
await mkdir(dirname(dist),{recursive:true});
await copyFile(resolve(outputDir,'client.js'),dist);
console.log(`Native Server client: ${output.length} bytes`);
